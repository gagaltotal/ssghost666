// --- Subdomain takeover detection -------------------------------------------
//
// Subdomain takeover is a DNS misconfiguration: a hostname's CNAME still
// points at a third-party service (GitHub Pages, Heroku, S3, Azure, ...)
// whose resource no longer exists. The service answers the dangling request
// with a distinctive "no such app / no such bucket / there isn't a site
// here" page, and because the vendor will happily hand that name to the
// first person who asks, an attacker can register it and serve content on
// the victim's own domain — with a perfectly valid TLS certificate.
//
// The check is deliberately cautious in two ways:
//
//   1. It only ever *reads*. It performs an alias lookup (CNAME) and a
//      single GET; it never attempts to claim, register or otherwise
//      provision anything at the provider. "Confirmed" here means the
//      provider's unclaimed-resource error page was observed, not that this
//      tool took the name over.
//   2. A dangling CNAME alone is *not* a finding. Many dangling aliases are
//      already safe because the provider now reserves the name, or because
//      a proxy masks the error. Every candidate must additionally produce
//      the provider's specific error signature, so a generic 404 from a
//      live service is never reported.
//
// DNS is resolved with the standard library only (net.LookupCNAME), so no
// new dependency is added.

// takeoverFingerprint maps a provider's CNAME suffix to the error signature
// its unclaimed-resource page emits. Signatures are the *stable* strings the
// vendor returns for a name nobody has claimed; a live resource would return
// real content instead.
//
// Every signature must be provider-specific. A bare "not found" or "404"
// would match half the internet and turn this check into a false-positive
// generator, so a generic phrase is only ever accepted when it is paired
// with a provider marker in the same inner slice.
type takeoverFingerprint struct {
	Service     string
	Suffixes    []string   // CNAME suffixes that identify this service
	Signatures  [][]string // every string in an inner slice must be present (case-insensitive)
	Severity    model.Severity
	Remediation string
}

