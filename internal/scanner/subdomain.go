// takeoverCandidate is one hostname whose CNAME chain we need to inspect.
type takeoverCandidate struct {
	Host  string // hostname as it appeared in the scan (no scheme/port)
	Fromd string // URL that produced the candidate, for evidence text
}

// findSubdomainCandidates collects the distinct hostnames the crawl
// discovered. Only hostnames (not IP literals) are considered, and the list
// is capped so a large crawl doesn't turn this into a heavy resolver sweep.
func findSubdomainCandidates(targets []model.Target, seedHost string) []takeoverCandidate {
	seen := map[string]bool{}
	var out []takeoverCandidate
	add := func(host, from string) {
		host = strings.ToLower(strings.TrimSpace(host))
		if host == "" || seen[host] || net.ParseIP(host) != nil {
			return // an IP literal cannot be taken over
		}
		seen[host] = true
		out = append(out, takeoverCandidate{Host: host, Fromd: from})
	}

	for _, t := range targets {
		u, err := url.Parse(t.URL)
		if err != nil {
			continue
		}
		add(u.Hostname(), t.URL)
	}
	// The seed host itself is the most valuable candidate even when the
	// crawl never linked to it directly.
	add(seedHost, "seed target")

	sort.Slice(out, func(i, j int) bool { return out[i].Host < out[j].Host })
	const maxCandidates = 40 // bounded resolver work: this is a recon check, not a DNS brute-forcer
	if len(out) > maxCandidates {
		out = out[:maxCandidates]
	}
	return out
}

// fingerprintFor returns the provider fingerprint whose CNAME suffix the
// given canonical name ends in, or nil.
func fingerprintFor(cname string) *takeoverFingerprint {
	low := strings.ToLower(strings.TrimSuffix(cname, "."))
	for i := range takeoverFingerprints {
		for _, s := range takeoverFingerprints[i].Suffixes {
			if low == s || strings.HasSuffix(low, "."+s) {
				return &takeoverFingerprints[i]
			}
		}
	}
	return nil
}

// cnameOf resolves the canonical name of a host, following the CNAME chain
// to its end. A host with only A/AAAA records returns the host itself (i.e.
// answers directly, so it is not a dangling-alias candidate). Resolution
// failure or an endless chain returns "".
func cnameOf(host string) string {
	seen := map[string]bool{}
	cur := host
	for i := 0; i < 8; i++ { // bounded: a deliberately long CNAME loop must not hang the scan
		if seen[cur] {
			return ""
		}
		seen[cur] = true
		cname, err := net.LookupCNAME(cur)
		if err != nil || cname == "" {
			return ""
		}
		cname = strings.TrimSuffix(cname, ".")
		if strings.EqualFold(cname, cur) {
			return cname
		}
		cur = cname
	}
	return cur
}

// matchesTakeoverSignature reports whether the response body is the
// provider's "resource does not exist" page. Every string in an inner slice
// must be present, so a partially-matching marketing page can't qualify.
func matchesTakeoverSignature(fp *takeoverFingerprint, body string, status int) (string, bool) {
	if status >= 500 {
		return "", false // a provider outage is not a dangling resource
	}
	low := strings.ToLower(body)
	for _, sig := range fp.Signatures {
		all := true
		for _, s := range sig {
			if !strings.Contains(low, s) {
				all = false
				break
			}
		}
		if all {
			return strings.Join(sig, " + "), true
		}
	}
	return "", false
}

// verifyDangling fetches the candidate over HTTPS (falling back to plaintext
// when the TLS handshake fails, which is common for a partially-provisioned
// dangling host — the same error page is served either way) and checks the
// body against the provider fingerprint.
func verifyDangling(ctx context.Context, lim *ratelimiter.Limiter, cli *httpclient.Client, host string, fp *takeoverFingerprint) (*httpclient.Exchange, string) {
	for _, u := range []string{"https://" + host + "/", "http://" + host + "/"} {
		if !lim.Acquire(ctx) {
			return nil, ""
		}
		ex := cli.Get(u)
		observeForAdaptive(lim, ex)
		lim.Release()
		if ex == nil || ex.Err != nil || ex.Response == nil {
			continue
		}
		if sig, ok := matchesTakeoverSignature(fp, ex.Body, ex.Response.StatusCode); ok {
			return ex, sig
		}
	}
	return nil, ""
}

// RunSubdomainTakeoverChecks inspects every discovered hostname for a
// dangling CNAME into a well-known third-party service and, when the
// provider's unclaimed-resource page is observed, reports it. It never
// attempts to claim anything.
func RunSubdomainTakeoverChecks(ctx context.Context, lim *ratelimiter.Limiter, cli *httpclient.Client, targets []model.Target) []model.Finding {
	seedHost := ""
	if origins := uniqueOrigins(targets); len(origins) > 0 {
		if u, err := url.Parse(origins[0]); err == nil {
			seedHost = u.Hostname()
		}
	} else if len(targets) > 0 {
		if u, err := url.Parse(targets[0].URL); err == nil {
			seedHost = u.Hostname()
		}
	}

	candidates := findSubdomainCandidates(targets, seedHost)
	if len(candidates) == 0 {
		return nil
	}

	var (
		mu       sync.Mutex
		findings []model.Finding
		wg       sync.WaitGroup
	)
	sem := make(chan struct{}, 8) // small fan-out: one DNS lookup + one HTTP request per host
	for _, cand := range candidates {
		cand := cand
		wg.Add(1)
		go func() {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()

			cname := cnameOf(cand.Host)
			if cname == "" {
				return
			}
			fp := fingerprintFor(cname)
			if fp == nil {
				return
			}

			ex, sig := verifyDangling(ctx, lim, cli, cand.Host, fp)
			if ex == nil || sig == "" {
				// Dangling CNAME but no provider error page: either the
				// resource was recreated or the provider now reserves the
				// name. Not enough evidence — stay silent.
				return
			}

			mu.Lock()
			findings = append(findings, model.Finding{
				Category: "Subdomain Takeover",
				Severity: fp.Severity,
				Title:    fmt.Sprintf("Subdomain takeover: %s is a dangling CNAME to %s", cand.Host, fp.Service),
				Description: fmt.Sprintf("%s resolves through a CNAME to %q, but %s answers with its unclaimed-resource error page. Because the underlying resource no longer exists, anyone who registers that name with %s can serve arbitrary content — including a valid TLS certificate for %s — on this hostname, enabling phishing, theft of cookies scoped to the parent domain, and bypass of domain-based allow-lists.",
					cand.Host, cname, fp.Service, fp.Service, cand.Host),
				URL:         "https://" + cand.Host + "/",
				Method:      "GET",
				Evidence:    model.Evidence{RequestRaw: ex.RequestRaw, ResponseRaw: ex.ResponseRaw, Notes: "CNAME chain: " + cand.Host + " -> " + cname + "; matched " + fp.Service + " unclaimed signature [" + sig + "]. Confirmed non-destructively: SSGhost666 did not register or claim the resource. Candidate first seen in " + cand.Fromd + "."},
				Remediation: fp.Remediation,
			})
			mu.Unlock()
		}()
	}
	wg.Wait()

	sort.Slice(findings, func(i, j int) bool {
		if findings[i].Severity.Rank() != findings[j].Severity.Rank() {
			return findings[i].Severity.Rank() < findings[j].Severity.Rank()
		}
		return findings[i].URL < findings[j].URL
	})
	return findings
}
